class Donor {
  final String id;
  final String name;
  final String lastName;
  final String email;
  final String password;
  final String bloodType;
  final String city;

  Donor({
    required this.id,
    required this.name,
    required this.lastName,
    required this.email,
    required this.password,
    required this.bloodType,
    required this.city,
  });
}
